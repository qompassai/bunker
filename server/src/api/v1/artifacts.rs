    #[tokio::test]
    async fn happy_path_stores_object_and_sets_latest() {
        let rig = rig("happy").await;
        let response = upload(&rig, &push_auth(), &default_request(), Body::from(BODY))
            .await
            .unwrap();

        assert_eq!(response.sha256, sha256_hex(BODY));
        assert_eq!(response.size, BODY.len() as u64);
        assert_eq!(response.name, "widget");
        assert_eq!(response.version, "1.0.0");

        let rows = artifact_rows(&rig).await;
        assert_eq!(rows.len(), 1);
        assert_eq!(rows[0].cache_id, rig.cache_id);
        assert_eq!(rows[0].size, BODY.len() as i64);
        assert_eq!(rows[0].content_type, "application/gzip");

        // The object is at the digest key, byte for byte.
        let digest: [u8; 32] = Sha256::digest(BODY).into();
        let key = artifact_key(rig.cache_id, &digest);
        let bytes = rig
            .storage
            .get_range(key, 0, BODY.len() as u64)
            .await
            .unwrap();
        assert_eq!(&bytes[..], BODY);

        // Latest points at the new artifact.
        let latest = rig
            .db
            .find_artifact_latest(rig.cache_id, "widget")
            .await
            .unwrap()
            .unwrap();
        assert_eq!(latest.id, rows[0].id);

        // The upload row resolved as completed, and nothing else
        // is in storage (the temp object is gone).
        let uploads = upload_rows(&rig).await;
        assert_eq!(uploads.len(), 1);
        assert_eq!(uploads[0].state, UPLOAD_STATE_COMPLETED);
        assert_eq!(stored_object_count(&rig.root), 1);

        tokio::fs::remove_dir_all(&rig.root).await.ok();
    }

