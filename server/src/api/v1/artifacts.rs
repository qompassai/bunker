/// Maximum length of an artifact name, in characters.
///
/// Mirrors the `artifact.name` column width (`varchar(50)`).
pub(crate) const MAX_NAME_LEN: usize = 50;

/// Maximum length of an artifact version, in characters.
///
/// Mirrors the `artifact.version` column width (`varchar(64)`).
pub(crate) const MAX_VERSION_LEN: usize = 64;

/// Maximum length of an artifact filename, in characters.
///
/// Mirrors the `artifact.filename` column width (`varchar(128)`).
pub(crate) const MAX_FILENAME_LEN: usize = 128;

/// How long an upload row is kept before it is considered stale.
///
/// Upload rows are bookkeeping, not artifacts; a row that never
/// resolves is garbage for a future cleanup pass. Nothing in M2
/// reaps them yet.
const UPLOAD_TTL_HOURS: i64 = 24;

/// The upload is being received.
const UPLOAD_STATE_RECEIVING: &str = "receiving";

/// The upload completed and produced an artifact.
const UPLOAD_STATE_COMPLETED: &str = "completed";

/// The upload failed and produced no artifact.
const UPLOAD_STATE_FAILED: &str = "failed";

/// Uploads one artifact.
///
/// Metadata arrives as JSON in the `X-Bunker-Artifact-Info`
/// header — the same header-metadata convention as the NAR
/// upload endpoint's `X-Bunker-Nar-Info` — because the request
/// body is the raw artifact bytes. The client may additionally
/// declare the `X-Bunker-Artifact-Sha256` and
/// `X-Bunker-Artifact-Size` headers; when present, the server
/// verifies what it received against them.
#[instrument(skip_all)]
pub(crate) async fn upload_artifact(
    Extension(state): Extension<State>,
    Extension(req_state): Extension<RequestState>,
    headers: HeaderMap,
    body: Body,
) -> ServerResult<Json<ArtifactUploadResponse>> {
    let request = parse_upload_request(&headers)?;
    let expected_sha256 = parse_expected_sha256(&headers)?;
    let expected_size = parse_expected_size(&headers)?;

    let database = state.database().await?;
    let storage = state.storage().await?;
    let params = UploadParams {
        request: &request,
        expected_sha256,
        expected_size,
        max_size: state.config().artifacts.max_size,
    };

    let response = upload_artifact_inner(
        database,
        storage.as_ref().as_ref(),
        &req_state.auth,
        &params,
        body,
    )
    .await?;

    Ok(Json(response))
}

/// The parameters of one artifact upload: what the client asked
/// for, what it declared about the body, and the server's limit.
pub(crate) struct UploadParams<'a> {
    /// The upload metadata from the `X-Bunker-Artifact-Info`
    /// header.
    pub(crate) request: &'a ArtifactUploadRequest,

    /// The SHA-256 digest the client declared for the body, if
    /// it declared one.
    pub(crate) expected_sha256: Option<[u8; 32]>,

    /// The size the client declared for the body, if it declared
    /// one.
    pub(crate) expected_size: Option<u64>,

    /// The server's maximum artifact size for this upload.
    pub(crate) max_size: u64,
}

/// The upload itself, split from the HTTP plumbing so tests can
/// drive it against a migrated database and a local backend.
///
/// Order of operations is contractual:
///
/// 1. Metadata is validated before anything is read or written.
/// 2. Authorization runs through the cache's existing `push`
///    permission. No upload row exists before this succeeds.
/// 3. The upload row is created, the body streamed to a
///    temporary key, and declared expectations verified.
/// 4. The artifact row and the `latest` pointer move in one
///    transaction; the object is then placed at its final key
///    and the upload row resolved.
pub(crate) async fn upload_artifact_inner(
    database: &DatabaseConnection,
    storage: &dyn StorageBackend,
    auth: &AuthState,
    params: &UploadParams<'_>,
    body: Body,
) -> ServerResult<ArtifactUploadResponse> {
    let request = params.request;

    validate_upload_request(request)?;

    if let Some(declared) = params.expected_size {
        if declared > params.max_size {
            return Err(ErrorKind::RequestError(anyhow!(
                "Declared artifact size {} exceeds the maximum artifact size of {} bytes",
                declared,
                params.max_size
            ))
            .into());
        }
    }

    let cache = auth
        .auth_cache(database, &request.cache, |cache, permission| {
            permission.require_push()?;
            Ok(cache)
        })
        .await?;

    let now = Utc::now();
    let upload = artifact_upload::ActiveModel {
        cache_id: Set(cache.id),
        name: Set(request.name.clone()),
        version: Set(request.version.clone()),
        filename: Set(request.filename.clone()),
        expected_sha256: Set(params.expected_sha256.map(|digest| digest.to_vec())),
        expected_size: Set(params.expected_size.map(|size| size as i64)),
        state: Set(UPLOAD_STATE_RECEIVING.to_owned()),
        created_at: Set(now),
        expires_at: Set(now + Duration::hours(UPLOAD_TTL_HOURS)),
        ..Default::default()
    }
    .insert(database)
    .await
    .map_err(ServerError::database_error)?;

    // From here on the upload row exists; every failure path must
    // resolve it as failed rather than leave it receiving forever.
    let result = receive_and_store(database, storage, cache.id, params, body).await;

    match result {
        Ok(response) => {
            set_upload_state(database, upload.id, UPLOAD_STATE_COMPLETED).await?;
            Ok(response)
        }
        Err(e) => {
            // The original error is the one the client needs; a
            // failure to record the failure must not mask it.
            let _ = set_upload_state(database, upload.id, UPLOAD_STATE_FAILED).await;
            Err(e)
        }
    }
}

/// Streams the body to a temporary storage key, verifies it,
/// records the artifact, and places the object at its final key.
async fn receive_and_store(
    database: &DatabaseConnection,
    storage: &dyn StorageBackend,
    cache_id: i64,
    params: &UploadParams<'_>,
    body: Body,
) -> ServerResult<ArtifactUploadResponse> {
    let request = params.request;
    let max_size = params.max_size;
    let now = Utc::now();

    // The temporary key is server-generated from a random UUID.
    // The final key is server-generated from the content digest.
    // User input is never part of either.
    let temp_key = format!("artifact-upload/{}", Uuid::new_v4());

    let received = Arc::new(AtomicU64::new(0));
    let exceeded = Arc::new(AtomicBool::new(false));
    let capped_stream = body.into_data_stream().map({
        let received = received.clone();
        let exceeded = exceeded.clone();
        move |result| {
            result
                .map_err(|e| io::Error::other(e.to_string()))
                .and_then(|chunk| {
                    let total = received.fetch_add(chunk.len() as u64, Ordering::SeqCst)
                        + chunk.len() as u64;
                    if total > max_size {
                        exceeded.store(true, Ordering::SeqCst);
                        Err(io::Error::new(
                            io::ErrorKind::InvalidData,
                            "artifact body exceeds the maximum artifact size",
                        ))
                    } else {
                        Ok(chunk)
                    }
                })
        }
    });
    let reader = StreamReader::new(capped_stream);
    let (mut hasher, finalized) = StreamHasher::new(reader, Sha256::new());

    if let Err(e) = storage.upload_file(temp_key.clone(), &mut hasher).await {
        // The object may be partially written; remove what is
        // there so a failed upload leaves no storage behind.
        let _ = storage.delete_file(temp_key).await;
        if exceeded.load(Ordering::SeqCst) {
            return Err(ErrorKind::RequestError(anyhow!(
                "Artifact body exceeds the maximum artifact size of {} bytes",
                max_size
            ))
            .into());
        }
        return Err(e);
    }

    let (digest_output, count) = finalized.get().ok_or_else(|| {
        ServerError::from(ErrorKind::StorageError(anyhow!(
            "Artifact stream was not finalized"
        )))
    })?;
    let mut sha256 = [0u8; 32];
    sha256.copy_from_slice(digest_output.as_ref());
    let size = *count as u64;

    if let Some(expected) = params.expected_sha256 {
        if expected != sha256 {
            let _ = storage.delete_file(temp_key).await;
            return Err(ErrorKind::RequestError(anyhow!(
                "SHA-256 mismatch: client declared {}, server computed {}",
                hex::encode(expected),
                hex::encode(sha256)
            ))
            .into());
        }
    }
    if let Some(expected) = params.expected_size {
        if expected != size {
            let _ = storage.delete_file(temp_key).await;
            return Err(ErrorKind::RequestError(anyhow!(
                "Size mismatch: client declared {} bytes, server received {} bytes",
                expected,
                size
            ))
            .into());
        }
    }

    let final_key = artifact_key(cache_id, &sha256);

    // Re-uploads are resolved before any state changes: identical
    // content under an identical (name, version, filename) is an
    // idempotent success, and the same triple with different
    // content is a conflict — versions are immutable once stored.
    let existing = Artifact::find()
        .filter(artifact::Column::CacheId.eq(cache_id))
        .filter(artifact::Column::Name.eq(request.name.as_str()))
        .filter(artifact::Column::Version.eq(request.version.as_str()))
        .filter(artifact::Column::Filename.eq(request.filename.as_str()))
        .one(database)
        .await
        .map_err(ServerError::database_error)?;

    if let Some(existing) = existing {
        if existing.sha256 != sha256.to_vec() {
            let _ = storage.delete_file(temp_key).await;
            return Err(ErrorKind::RequestError(anyhow!(
                "An artifact named {} {} ({}) already exists with different contents",
                request.name,
                request.version,
                request.filename
            ))
            .into());
        }

        // Heal an object that never made it to its final key
        // (e.g. an earlier upload died after its transaction
        // committed); otherwise the temp copy is redundant.
        if storage.get_range(final_key.clone(), 0, 1).await.is_ok() {
            let _ = storage.delete_file(temp_key).await;
        } else {
            move_object(storage, &temp_key, &final_key).await?;
        }

        return Ok(response_from(request, &existing));
    }

    // Identical content under a different name needs no second
    // copy of the object.
    let digest_exists = Artifact::find()
        .filter(artifact::Column::CacheId.eq(cache_id))
        .filter(artifact::Column::Sha256.eq(sha256.to_vec()))
        .one(database)
        .await
        .map_err(ServerError::database_error)?;
    let object_present =
        digest_exists.is_some() && storage.get_range(final_key.clone(), 0, 1).await.is_ok();

    // The artifact row and the `latest` pointer move together or
    // not at all, so `latest` can never name an artifact that was
    // not fully recorded.
    let txn = database
        .begin()
        .await
        .map_err(ServerError::database_error)?;

    let artifact = artifact::ActiveModel {
        cache_id: Set(cache_id),
        name: Set(request.name.clone()),
        version: Set(request.version.clone()),
        filename: Set(request.filename.clone()),
        size: Set(size as i64),
        sha256: Set(sha256.to_vec()),
        content_type: Set(artifact_content_type(&request.filename).to_owned()),
        created_at: Set(now),
        updated_at: Set(now),
        ..Default::default()
    }
    .insert(&txn)
    .await
    .map_err(ServerError::database_error)?;

    ArtifactLatest::insert(artifact_latest::ActiveModel {
        cache_id: Set(cache_id),
        name: Set(request.name.clone()),
        latest_artifact_id: Set(artifact.id),
    })
    .on_conflict(
        OnConflict::columns([
            artifact_latest::Column::CacheId,
            artifact_latest::Column::Name,
        ])
        .update_columns([artifact_latest::Column::LatestArtifactId])
        .to_owned(),
    )
    .exec(&txn)
    .await
    .map_err(ServerError::database_error)?;

    txn.commit().await.map_err(ServerError::database_error)?;

    if object_present {
        let _ = storage.delete_file(temp_key).await;
    } else {
        move_object(storage, &temp_key, &final_key).await?;
    }

    Ok(response_from(request, &artifact))
}

/// Moves an object between two storage keys by streaming it
/// through the backend's download/upload pair.
///
/// Placement happens after the artifact's transaction commits
/// (the recorded order for this endpoint). If it fails, the
/// artifact row names an object that is not there yet; a retry
/// of the same upload detects the missing object and heals it
/// instead of failing as a duplicate.
async fn move_object(storage: &dyn StorageBackend, from: &str, to: &str) -> ServerResult<()> {
    match storage.download_file(from.to_owned(), true).await? {
        Download::AsyncRead(mut reader) => {
            storage.upload_file(to.to_owned(), &mut reader).await?;
        }
        Download::Url(_) => {
            return Err(ErrorKind::StorageError(anyhow!(
                "Storage backend returned a URL for an internal object move"
            ))
            .into());
        }
    }

    storage.delete_file(from.to_owned()).await?;

    Ok(())
}

/// Records the terminal state of an upload row.
async fn set_upload_state(
    database: &DatabaseConnection,
    upload_id: i64,
    state: &str,
) -> ServerResult<()> {
    ArtifactUpload::update(artifact_upload::ActiveModel {
        id: Set(upload_id),
        state: Set(state.to_owned()),
        ..Default::default()
    })
    .exec(database)
    .await
    .map_err(ServerError::database_error)?;

    Ok(())
}

/// Builds the response from the recorded artifact.
fn response_from(
    request: &ArtifactUploadRequest,
    artifact: &artifact::Model,
) -> ArtifactUploadResponse {
    ArtifactUploadResponse {
        cache: request.cache.clone(),
        name: artifact.name.clone(),
        version: artifact.version.clone(),
        filename: artifact.filename.clone(),
        sha256: hex::encode(&artifact.sha256),
        size: artifact.size as u64,
    }
}

/// The stored content type for an artifact filename.
///
/// Artifacts are opaque to the server; the type is recorded for
/// the download side (M3) from the filename extension, defaulting
/// to `application/octet-stream`.
fn artifact_content_type(filename: &str) -> &'static str {
    let lower = filename.to_ascii_lowercase();
    if lower.ends_with(".tar.gz") || lower.ends_with(".tgz") {
        "application/gzip"
    } else if lower.ends_with(".tar.zst") {
        "application/zstd"
    } else if lower.ends_with(".tar.xz") {
        "application/x-xz"
    } else if lower.ends_with(".tar") {
        "application/x-tar"
    } else if lower.ends_with(".zip") {
        "application/zip"
    } else if lower.ends_with(".json") {
        "application/json"
    } else if lower.ends_with(".txt") {
        "text/plain"
    } else {
        "application/octet-stream"
    }
}

/// Validates upload metadata before any storage or database
/// write, and before authorization.
///
/// The bounds mirror the schema: name ≤ 50, version ≤ 64,
/// filename ≤ 128 characters. The charset is deliberately
/// strict — ASCII alphanumerics plus `.`, `_`, `-`, `+` — which
/// by construction excludes path separators, control characters,
/// and whitespace from every field. The filename additionally
/// may not contain `..`.
fn validate_upload_request(request: &ArtifactUploadRequest) -> ServerResult<()> {
    validate_artifact_tokens(&request.name, &request.version, &request.filename)
}

/// Validates the `(name, version, filename)` tokens that address
/// an artifact.
///
/// This is the one validation discipline for the artifact
/// namespace: the upload endpoint runs it before any write, and
/// the download endpoint (`crate::api::artifacts`) runs the same
/// function before any read, so a token that could not have been
/// uploaded can never address a read either.
pub(crate) fn validate_artifact_tokens(
    name: &str,
    version: &str,
    filename: &str,
) -> ServerResult<()> {
    validate_field("name", name, MAX_NAME_LEN)?;
    validate_field("version", version, MAX_VERSION_LEN)?;
    validate_field("filename", filename, MAX_FILENAME_LEN)?;

    if filename.contains("..") || filename == "." {
        return Err(ErrorKind::RequestError(anyhow!(
            "Invalid filename {:?}: must be a bare filename",
            filename
        ))
        .into());
    }

    Ok(())
}

/// Validates one metadata field against its bound and charset.
fn validate_field(field: &str, value: &str, max_len: usize) -> ServerResult<()> {
    if value.is_empty() {
        return Err(
            ErrorKind::RequestError(anyhow!("Artifact {} must not be empty", field)).into(),
        );
    }

    if value.chars().count() > max_len {
        return Err(ErrorKind::RequestError(anyhow!(
            "Artifact {} is {} characters, exceeding the maximum of {}",
            field,
            value.chars().count(),
            max_len
        ))
        .into());
    }

    if !value
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-' | b'+'))
    {
        return Err(ErrorKind::RequestError(anyhow!(
            "Invalid artifact {} {:?}: only ASCII letters, digits, '.', '_', '-' and '+' are allowed",
            field,
            value
        ))
        .into());
    }

    Ok(())
}

/// Parses the `X-Bunker-Artifact-Info` header.
fn parse_upload_request(headers: &HeaderMap) -> ServerResult<ArtifactUploadRequest> {
    let value = headers.get(BUNKER_ARTIFACT_INFO).ok_or_else(|| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "Missing the {} header",
            BUNKER_ARTIFACT_INFO
        )))
    })?;

    let text = value.to_str().map_err(|_| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "The {} header is not valid text",
            BUNKER_ARTIFACT_INFO
        )))
    })?;

    serde_json::from_str(text).map_err(|e| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "Could not parse the {} header: {}",
            BUNKER_ARTIFACT_INFO,
            e
        )))
    })
}

/// Parses the optional `X-Bunker-Artifact-Sha256` header.
fn parse_expected_sha256(headers: &HeaderMap) -> ServerResult<Option<[u8; 32]>> {
    let Some(value) = headers.get(BUNKER_ARTIFACT_SHA256) else {
        return Ok(None);
    };

    let text = value.to_str().map_err(|_| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "The {} header is not valid text",
            BUNKER_ARTIFACT_SHA256
        )))
    })?;

    let bytes = hex::decode(text).map_err(|_| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "The {} header is not valid hex",
            BUNKER_ARTIFACT_SHA256
        )))
    })?;

    let digest: [u8; 32] = bytes.try_into().map_err(|_| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "The {} header must decode to 32 bytes",
            BUNKER_ARTIFACT_SHA256
        )))
    })?;

    Ok(Some(digest))
}

/// Parses the optional `X-Bunker-Artifact-Size` header.
fn parse_expected_size(headers: &HeaderMap) -> ServerResult<Option<u64>> {
    let Some(value) = headers.get(BUNKER_ARTIFACT_SIZE) else {
        return Ok(None);
    };

    let text = value.to_str().map_err(|_| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "The {} header is not valid text",
            BUNKER_ARTIFACT_SIZE
        )))
    })?;

    let size: u64 = text.parse().map_err(|_| {
        ServerError::from(ErrorKind::RequestError(anyhow!(
            "The {} header is not a valid size",
            BUNKER_ARTIFACT_SIZE
        )))
    })?;

    Ok(Some(size))
}

