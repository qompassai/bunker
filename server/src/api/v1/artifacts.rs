    #[test]
    fn invalid_jwt_is_rejected() {
        let key = Ed25519KeyPair::generate();
        let signature = SignatureType::EdDSA(Box::new(key));
        let exp = Utc::now() + Duration::days(1);

        // Garbage is not a token.
        assert!(Token::from_jwt("not-a-jwt", &signature, &None, &None).is_err());

        // A well-formed token signed by a different key is
        // rejected — this is the state a request with an invalid
        // JWT ends in: anonymous, and denied by the handler.
        let other_key = Ed25519KeyPair::generate();
        let foreign = Token::new("mallory".to_owned(), &exp)
            .encode(&SignatureType::EdDSA(Box::new(other_key)), &None, &None)
            .unwrap();
        assert!(Token::from_jwt(&foreign, &signature, &None, &None).is_err());

        // Validation: the genuine round trip verifies.
        let genuine = Token::new("artifact-tester".to_owned(), &exp)
            .encode(&signature, &None, &None)
            .unwrap();
        assert!(Token::from_jwt(&genuine, &signature, &None, &None).is_ok());
    }

    #[tokio::test]
    async fn traversal_and_separator_filenames_are_rejected() {
        let rig = rig("traversal").await;
        let auth = push_auth();

        for filename in [
            "../evil.tar.gz",
            "..",
            ".",
            "a/b.tar.gz",
            "a\\b.tar.gz",
            "widget..tar.gz",
            "/absolute.tar.gz",
            "name with spaces.tar.gz",
            "tab\tname.tar.gz",
        ] {
            let req = request("widget", "1.0.0", filename);
            let result = upload(&rig, &auth, &req, Body::from(BODY)).await;
            assert!(result.is_err(), "filename {:?} must be rejected", filename);
        }

        // Separators in the other fields are rejected by the same
        // charset.
        for req in [
            request("wid/get", "1.0.0", "widget.tar.gz"),
            request("widget", "1 0 0", "widget.tar.gz"),
            request("widget", "1.0.0", ""),
        ] {
            let result = upload(&rig, &auth, &req, Body::from(BODY)).await;
            assert!(result.is_err());
        }

        // Validation precedes every write.
        assert_eq!(artifact_rows(&rig).await.len(), 0);
        assert_eq!(upload_rows(&rig).await.len(), 0);
        assert_eq!(stored_object_count(&rig.root), 0);

        tokio::fs::remove_dir_all(&rig.root).await.ok();
    }

