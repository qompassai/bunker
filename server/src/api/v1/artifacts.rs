    fn auth_with(push: bool, pull: bool) -> AuthState {
        let mut token = Token::new(
            "artifact-tester".to_owned(),
            &(Utc::now() + Duration::days(1)),
        );
        let cache = CacheName::new(CACHE_NAME.to_owned()).unwrap();
        let permission = token.get_or_insert_permission_mut(cache.to_pattern());
        permission.push = push;
        permission.pull = pull;

        let auth = AuthState::new();
        auth.token.set(token).unwrap();
        auth
    }

    fn push_auth() -> AuthState {
        auth_with(true, false)
    }

    async fn upload(
        rig: &Rig,
        auth: &AuthState,
        request: &ArtifactUploadRequest,
        body: Body,
    ) -> ServerResult<ArtifactUploadResponse> {
        upload_artifact_inner(
            &rig.db,
            &rig.storage,
            auth,
            &UploadParams {
                request,
                expected_sha256: None,
                expected_size: None,
                max_size: 1 << 30,
            },
            body,
        )
        .await
    }

    async fn artifact_rows(rig: &Rig) -> Vec<artifact::Model> {
        Artifact::find().all(&rig.db).await.unwrap()
    }

    async fn upload_rows(rig: &Rig) -> Vec<artifact_upload::Model> {
        ArtifactUpload::find().all(&rig.db).await.unwrap()
    }

    /// Counts files under the storage root, excluding the
    /// backend's VERSION marker — i.e. counts stored objects.
    fn stored_object_count(root: &Path) -> usize {
        fn walk(dir: &Path) -> usize {
            let mut count = 0;
            if let Ok(entries) = std::fs::read_dir(dir) {
                for entry in entries.flatten() {
                    let path = entry.path();
                    if path.is_dir() {
                        count += walk(&path);
                    } else if entry.file_name() != "VERSION" {
                        count += 1;
                    }
                }
            }
            count
        }

        walk(&root.join("storage"))
    }

    fn sha256_hex(data: &[u8]) -> String {
        hex::encode(Sha256::digest(data))
    }

